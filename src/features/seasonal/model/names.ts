/** «cherries» → «cherry», «tomatoes» → «tomato», «peaches» → «peach», «carrots» → «carrot». */
export function englishSingular(name: string): string {
  if (/ies$/i.test(name)) return name.replace(/ies$/i, 'y');
  if (/(oes|ches|shes)$/i.test(name)) return name.replace(/es$/i, '');
  return name.replace(/s$/i, '');
}

/** Name of a seasonal food in the active language. */
export function foodName(slug: string): string {
  const locale = getLocale();
  const translated = locale === 'en' ? FOOD_NAMES_EN[slug] : locale === 'sv' ? FOOD_NAMES_SV[slug] : undefined;
  return translated ?? FOODS_BY_SLUG.get(slug)?.name ?? slug;
}
